// Extracts the 63 page-spec panels and 28 document panels from the board copy into design/final/spec/.
// Source-level only: runs the board's first three inline scripts in node:vm (no DOM, no require, no process).
// Usage (from repo root): node design/final/tools/extract_board.mjs            write spec/ files
//                         node design/final/tools/extract_board.mjs --verify   write nothing; assert and exit 0/1
import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";
import { BOARD_BYTES, BOARD_COPY, BOARD_ORIGINAL_NAME, SPEC_DIR, rel } from "./schema.mjs";

const EXPECTED = Object.freeze({ entries: 211, drawn: 120, spec: 63, document: 28, zips: 91, pages: 63, journeys: 12 });
const SCRIPT_RE = /<script\b[^>]*>([\s\S]*?)<\/script>/g;
const VM_TIMEOUT_MS = 20000;

export const sha256 = (data) => crypto.createHash("sha256").update(data).digest("hex");
export const slugify = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
export const json = (value) => JSON.stringify(value, null, 2) + "\n";

const kindOf = (sec) => (sec === "N" ? "spec" : sec === "M" || sec === "Q" ? "document" : "drawn");
// Same device rule as the board's own coverage counter (board line 1698).
const deviceOf = (name) => (/iPhone/.test(name) ? "iPhone" : /iPad/.test(name) ? "iPad" : "PC");
const pageIdOf = (name) => (name.match(/^([WO]\d\d)/) || [])[1] || null;

// Runs board scripts 1–3 in one empty context, then reads S, PAGES, JOURNEYS and ZIPS out as plain data.
// A2 held: the scripts run without any document stub (sbAuto() is defined but never called at load).
export function runBoard(text) {
  const scripts = [...text.matchAll(SCRIPT_RE)].map((m) => m[1]);
  if (scripts.length !== 4) throw new Error(`${BOARD_COPY}: expected 4 inline scripts, found ${scripts.length}`);
  const context = vm.createContext({});
  scripts.slice(0, 3).forEach((src, i) => vm.runInContext(src, context, { timeout: VM_TIMEOUT_MS, filename: `board-script-${i + 1}` }));
  const out = vm.runInContext("JSON.stringify({ S: S.map(({ sec, name, note, html }) => ({ sec, name, note, html })), PAGES, JOURNEYS, zips: ZIPS.length })", context, { timeout: VM_TIMEOUT_MS });
  return JSON.parse(out);
}

export function classify(board) {
  const entries = board.S.map((s, i) => {
    const kind = kindOf(s.sec);
    const pageId = kind === "document" ? null : pageIdOf(s.name);
    return Object.freeze({ n: i + 1, sec: s.sec, name: s.name, note: s.note, html: s.html, kind, page_id: pageId, device: kind === "drawn" ? deviceOf(s.name) : null });
  });
  const count = (k) => entries.filter((e) => e.kind === k).length;
  const counts = { entries: entries.length, drawn: count("drawn"), spec: count("spec"), document: count("document"), zips: board.zips, pages: board.PAGES.length, journeys: board.JOURNEYS.length };
  return { entries, counts };
}

export function countErrors(counts, board) {
  const errors = Object.entries(EXPECTED).filter(([k, v]) => counts[k] !== v).map(([k, v]) => `${BOARD_COPY}: count ${k} expected ${v}, actual ${counts[k]}`);
  const journeyIds = board.JOURNEYS.map((j) => j[0]).join(",");
  const wantJourneys = Array.from({ length: 12 }, (_, i) => `J${String(i + 1).padStart(2, "0")}`).join(",");
  if (journeyIds !== wantJourneys) errors.push(`${BOARD_COPY}: JOURNEYS expected ${wantJourneys}, actual ${journeyIds}`);
  return errors;
}

function specPageErrors(entries, pages) {
  const specIds = entries.filter((e) => e.kind === "spec").map((e) => e.page_id);
  const pageIds = pages.map((p) => p[0]);
  const dup = specIds.filter((id, i) => specIds.indexOf(id) !== i);
  const missing = pageIds.filter((id) => !specIds.includes(id));
  const extra = specIds.filter((id) => !pageIds.includes(id));
  return [
    ...(dup.length ? [`spec panels: duplicate page ids ${dup.join(",")}`] : []),
    ...(missing.length ? [`spec panels: no panel for ${missing.join(",")}`] : []),
    ...(extra.length ? [`spec panels: panel for unknown page ${extra.join(",")}`] : []),
  ];
}

const header = (e) => `<!-- generated by extract_board.mjs from board sec ${e.sec}: ${e.name} -->\n`;

// Builds every spec/ file in memory: Map of path relative to spec/ -> string.
export function buildSpecFiles(boardBuf) {
  const board = runBoard(boardBuf.toString("utf8"));
  const { entries, counts } = classify(board);
  const errors = [...countErrors(counts, board), ...specPageErrors(entries, board.PAGES)];
  if (errors.length) throw new Error(`board-count variance (stop and report):\n  ${errors.join("\n  ")}`);
  const docs = entries.filter((e) => e.kind === "document");
  const fileOf = (e) => (e.kind === "spec" ? `pages/${e.page_id}.html` : `docs/${String(docs.indexOf(e) + 1).padStart(2, "0")}-${slugify(e.name)}.html`);
  const panels = entries.filter((e) => e.kind !== "drawn").map((e) => ({ e, file: fileOf(e), body: header(e) + e.html }));
  const index = panels.map(({ e, file, body }) => ({ kind: e.kind, sec: e.sec, name: e.name, note: e.note, page_id: e.page_id, file, bytes: Buffer.byteLength(body), sha256: sha256(body) }));
  const manifest = {
    source: { file: path.basename(BOARD_COPY), bytes: boardBuf.length, sha256: sha256(boardBuf) },
    counts,
    entries: entries.map(({ n, sec, name, kind, page_id, device }) => ({ n, sec, name, kind, page_id, device })),
    pages: board.PAGES.map(([id, name, roles, priority]) => ({ id, name, roles, priority })),
    journeys: board.JOURNEYS.map(([id, name, pages]) => ({ id, name, pages })),
  };
  const files = new Map(panels.map(({ file, body }) => [file, body]));
  return new Map([...files, ["index.json", json(index)], ["board_manifest.json", json(manifest)]]);
}

const listFiles = (dir, prefix = "") => (fs.existsSync(dir) ? fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) => (d.isDirectory() ? listFiles(path.join(dir, d.name), `${prefix}${d.name}/`) : [`${prefix}${d.name}`])) : []);

function writeSpec(files) {
  const specDir = rel(SPEC_DIR);
  const stale = listFiles(specDir).filter((f) => !files.has(f));
  if (stale.length) throw new Error(`${SPEC_DIR}: unexpected files ${stale.join(",")} (remove them deliberately, then rerun)`);
  for (const [file, body] of files) {
    fs.mkdirSync(path.dirname(path.join(specDir, file)), { recursive: true });
    fs.writeFileSync(path.join(specDir, file), body);
  }
  console.log(`extract_board: wrote ${files.size} files to ${SPEC_DIR}`);
}

function verify(boardBuf, files) {
  const errors = [];
  const manifestPath = rel(SPEC_DIR, "board_manifest.json");
  const pinned = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, "utf8")).source?.sha256 : null;
  if (boardBuf.length !== BOARD_BYTES) errors.push(`${BOARD_COPY}: expected ${BOARD_BYTES} bytes, actual ${boardBuf.length}`);
  if (sha256(boardBuf) !== pinned) errors.push(`${BOARD_COPY}: sha256 ${sha256(boardBuf)} does not equal pinned ${pinned}`);
  const original = path.join(os.homedir(), "Downloads", BOARD_ORIGINAL_NAME);
  if (!fs.existsSync(original)) console.log("original not present; verified against pinned sha256");
  else if (!fs.readFileSync(original).equals(boardBuf)) errors.push(`${original}: differs from ${BOARD_COPY}`);
  const onDisk = listFiles(rel(SPEC_DIR));
  for (const f of onDisk.filter((f) => !files.has(f))) errors.push(`${SPEC_DIR}/${f}: extra file, not in a fresh extraction`);
  for (const [f, body] of files) {
    const p = rel(SPEC_DIR, f);
    if (!fs.existsSync(p)) errors.push(`${SPEC_DIR}/${f}: missing`);
    else if (!fs.readFileSync(p).equals(Buffer.from(body))) errors.push(`${SPEC_DIR}/${f}: differs from a fresh extraction`);
  }
  return errors;
}

function main(argv) {
  const boardBuf = fs.readFileSync(rel(BOARD_COPY));
  const files = buildSpecFiles(boardBuf);
  const counts = JSON.parse(files.get("board_manifest.json")).counts;
  const summary = `${counts.entries} = ${counts.drawn} + ${counts.spec} + ${counts.document}; ZIPS ${counts.zips}; ${counts.pages} pages; ${counts.journeys} journeys`;
  if (!argv.includes("--verify")) { writeSpec(files); console.log(`extract_board: ${summary}`); return 0; }
  const errors = verify(boardBuf, files);
  if (errors.length) { console.error(`extract_board --verify FAILED (${errors.length}):\n  ${errors.join("\n  ")}`); return 1; }
  console.log(`extract_board --verify passed: ${summary}; ${files.size} spec files byte-identical; board ${boardBuf.length} bytes, sha256 pinned.`);
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { process.exitCode = main(process.argv.slice(2)); } catch (e) { console.error(`extract_board: ${e.message}`); process.exitCode = 1; }
}
